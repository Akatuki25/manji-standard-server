#!/usr/bin/env node
/**
 * mss-protoc-gen
 *
 * proto メッセージの `@entity` マーカーから DDD の 3 ファイルを生成するカスタムプラグイン。
 *
 * 出力（`out:` ディレクトリ相対）:
 *   - src/domain/entity/<kebab>.gen.ts         : Entity クラス + static create（バリデーション）
 *   - src/domain/repository/<kebab>-repository.gen.ts : Repository interface
 *   - src/infra/repository/in-memory-<kebab>-repository.gen.ts : InMemory 実装
 *
 * コメントマーカー:
 *   @entity     メッセージに付与
 *   @pk         フィールドに付与。findById 相当を生成
 *   @unique     フィールドに付与。findBy<Field> を追加生成
 *   @email      フィールドに付与。email 形式バリデーション
 *   @required   フィールドに付与。非空バリデーション
 *   @timestamp  int64 フィールドに付与。Date 型にマップし、フィールド名末尾の Unix を除去
 */
import { createEcmaScriptPlugin, runNodeJs } from "@bufbuild/protoplugin";
import { localName } from "@bufbuild/protoplugin/ecmascript";

const plugin = createEcmaScriptPlugin({
  name: "mss-protoc-gen",
  version: "v0.1.0",
  generateTs(schema) {
    for (const file of schema.files) {
      for (const message of file.messages) {
        const entity = parseEntity(message);
        if (!entity) continue;
        generateEntity(schema, entity);
        generateRepository(schema, entity);
        generateInfraRepository(schema, entity);
      }
    }
  },
});

runNodeJs(plugin);

// ==================== parsing ====================

function hasMarker(text, marker) {
  if (!text) return false;
  for (const line of text.split("\n")) {
    const tokens = line.replace(/^\s*\/\/\s*/, "").trim().split(/\s+/);
    if (tokens.includes(marker)) return true;
  }
  return false;
}

function parseEntity(message) {
  const leading = message.getComments().leading ?? "";
  if (!hasMarker(leading, "@entity")) return null;

  const fields = [];
  let pkField = null;
  const uniqueFields = [];

  for (const field of message.fields) {
    const comment = field.getComments().leading ?? "";
    const isPk = hasMarker(comment, "@pk");
    const isUnique = hasMarker(comment, "@unique");
    const isEmail = hasMarker(comment, "@email");
    const isRequired = hasMarker(comment, "@required");
    const isTimestamp = hasMarker(comment, "@timestamp");

    let tsType = "string";
    let tsName = localName(field);

    if (isTimestamp) {
      tsType = "Date";
      // createdAtUnix → createdAt
      tsName = tsName.replace(/Unix$/, "");
    } else {
      // field.scalar は enum value。proto type 名に変換
      switch (field.scalar) {
        case 9: // STRING
          tsType = "string";
          break;
        case 5: // INT32
        case 3: // INT64
        case 13: // UINT32
        case 4: // UINT64
          tsType = "number";
          break;
        case 8: // BOOL
          tsType = "boolean";
          break;
        default:
          tsType = "string";
      }
    }

    const spec = {
      name: tsName,
      type: tsType,
      isPk,
      isUnique,
      isEmail,
      isRequired,
      isTimestamp,
    };
    fields.push(spec);
    if (isPk) pkField = spec;
    if (isUnique) uniqueFields.push(spec);
  }

  if (!pkField) return null;

  const entityName = message.name; // PascalCase e.g. "User"
  return {
    name: entityName,
    kebab: pascalToKebab(entityName),
    fields,
    pkField,
    uniqueFields,
  };
}

// ==================== generators ====================

function generateEntity(schema, e) {
  const f = schema.generateFile(`src/domain/entity/${e.kebab}.gen.ts`);
  f.print(`// Code generated by mss-protoc-gen. DO NOT EDIT.`);
  f.print();
  f.print(`export type ${e.name}Props = {`);
  for (const field of e.fields) {
    f.print(`  ${field.name}: ${field.type};`);
  }
  f.print(`};`);
  f.print();
  f.print(`export class ${e.name} {`);
  for (const field of e.fields) {
    f.print(`  readonly ${field.name}: ${field.type};`);
  }
  f.print();
  f.print(`  private constructor(props: ${e.name}Props) {`);
  for (const field of e.fields) {
    f.print(`    this.${field.name} = props.${field.name};`);
  }
  f.print(`  }`);
  f.print();
  f.print(`  static create(props: ${e.name}Props): ${e.name} {`);
  for (const field of e.fields) {
    if (field.isPk) {
      f.print(`    if (!props.${field.name}) {`);
      f.print(`      throw new Error("${field.name} is required");`);
      f.print(`    }`);
    }
    if (field.isRequired && field.type === "string") {
      f.print(`    const ${field.name} = props.${field.name}.trim();`);
      f.print(`    if (!${field.name}) {`);
      f.print(`      throw new Error("${field.name} is required");`);
      f.print(`    }`);
    }
    if (field.isEmail) {
      f.print(`    const ${field.name} = props.${field.name}.trim();`);
      f.print(`    if (!${field.name} || !${field.name}.includes("@")) {`);
      f.print(`      throw new Error("${field.name} is invalid");`);
      f.print(`    }`);
    }
  }
  f.print(`    return new ${e.name}({`);
  for (const field of e.fields) {
    // 検証で新変数を作ったフィールドはそちらを、それ以外は props から
    const needsLocal =
      (field.isEmail || (field.isRequired && field.type === "string"));
    if (needsLocal) {
      f.print(`      ${field.name},`);
    } else {
      f.print(`      ${field.name}: props.${field.name},`);
    }
  }
  f.print(`    });`);
  f.print(`  }`);
  f.print(`}`);
}

function generateRepository(schema, e) {
  const f = schema.generateFile(`src/domain/repository/${e.kebab}-repository.gen.ts`);
  f.print(`// Code generated by mss-protoc-gen. DO NOT EDIT.`);
  f.print();
  f.print(`import type { ${e.name} } from "../entity/${e.kebab}.gen.js";`);
  f.print();
  f.print(`export interface ${e.name}Repository {`);
  f.print(`  save(${e.name.toLowerCase()}: ${e.name}): Promise<void>;`);
  f.print(`  findBy${capitalize(e.pkField.name)}(${e.pkField.name}: ${e.pkField.type}): Promise<${e.name} | null>;`);
  for (const u of e.uniqueFields) {
    if (u.isPk) continue;
    f.print(`  findBy${capitalize(u.name)}(${u.name}: ${u.type}): Promise<${e.name} | null>;`);
  }
  f.print(`}`);
}

function generateInfraRepository(schema, e) {
  const f = schema.generateFile(`src/infra/repository/in-memory-${e.kebab}-repository.gen.ts`);
  const className = `InMemory${e.name}Repository`;

  f.print(`// Code generated by mss-protoc-gen. DO NOT EDIT.`);
  f.print();
  f.print(`import type { ${e.name} } from "../../domain/entity/${e.kebab}.gen.js";`);
  f.print(`import type { ${e.name}Repository } from "../../domain/repository/${e.kebab}-repository.gen.js";`);
  f.print();
  f.print(`export class ${className} implements ${e.name}Repository {`);
  f.print(`  private readonly items = new Map<${e.pkField.type}, ${e.name}>();`);
  f.print();
  f.print(`  async save(${e.name.toLowerCase()}: ${e.name}): Promise<void> {`);
  f.print(`    this.items.set(${e.name.toLowerCase()}.${e.pkField.name}, ${e.name.toLowerCase()});`);
  f.print(`  }`);
  f.print();
  f.print(`  async findBy${capitalize(e.pkField.name)}(${e.pkField.name}: ${e.pkField.type}): Promise<${e.name} | null> {`);
  f.print(`    return this.items.get(${e.pkField.name}) ?? null;`);
  f.print(`  }`);
  for (const u of e.uniqueFields) {
    if (u.isPk) continue;
    f.print();
    f.print(`  async findBy${capitalize(u.name)}(${u.name}: ${u.type}): Promise<${e.name} | null> {`);
    f.print(`    for (const item of this.items.values()) {`);
    f.print(`      if (item.${u.name} === ${u.name}) return item;`);
    f.print(`    }`);
    f.print(`    return null;`);
    f.print(`  }`);
  }
  f.print(`}`);
}

// ==================== helpers ====================

function pascalToKebab(s) {
  return s.replace(/([a-z0-9])([A-Z])/g, "$1-$2").toLowerCase();
}

function capitalize(s) {
  return s.charAt(0).toUpperCase() + s.slice(1);
}
